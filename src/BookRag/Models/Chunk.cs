namespace BookRag.Models;

/// <summary>
/// The fundamental unit of the knowledge base.
/// A Chunk is a short passage of text together with its embedding vector
/// and enough metadata to cite the original source in an answer.
/// </summary>
public class Chunk
{
    /// <summary>Unique sequential identifier within the vector store.</summary>
    public int Id { get; set; }

    /// <summary>
    /// Human-readable label for where this chunk came from.
    /// For TXT/PDF files this is typically a chapter or section heading.
    /// For web pages it is the page title.
    /// </summary>
    public string Source { get; set; } = "";

    /// <summary>What kind of document this chunk came from.</summary>
    public SourceType SourceType { get; set; } = SourceType.Text;

    /// <summary>Original filename for TXT and PDF sources.</summary>
    public string? FileName { get; set; }

    /// <summary>
    /// Page number for PDF sources (1-based).
    /// Null for TXT and web chunks.
    /// </summary>
    public int? PageNumber { get; set; }

    /// <summary>
    /// Originating URL for web sources.
    /// Null for file-based chunks.
    /// </summary>
    public string? Url { get; set; }

    /// <summary>
    /// The actual passage text that is passed to the LLM as context.
    /// For PDF chunks this includes a "[Page N]" prefix so the LLM can
    /// cite page numbers accurately.
    /// </summary>
    public string Text { get; set; } = "";

    /// <summary>
    /// Embedding vector generated by the embedding model.
    /// Serialised to JSON for persistent storage.
    /// </summary>
    public float[]? Embedding { get; set; }

    /// <summary>
    /// Name/identifier of the embedding model used to produce
    /// <see cref="Embedding"/>.  Stored so the query command can warn
    /// (or refuse) if the current model differs from the one at ingest time.
    /// </summary>
    public string? EmbeddingModel { get; set; }

    // ── Convenience ──────────────────────────────────────────────────────────

    /// <summary>
    /// Returns a short, human-readable citation string suitable for
    /// inclusion in an LLM response.
    /// </summary>
    public string ToCitationString() => SourceType switch
    {
        SourceType.Pdf  => PageNumber.HasValue
                           ? $"{FileName}, page {PageNumber}"
                           : FileName ?? Source,
        SourceType.Web  => Url ?? Source,
        _               => FileName is not null ? $"{FileName} — {Source}" : Source
    };
}

/// <summary>Discriminator for the kind of document a chunk was extracted from.</summary>
public enum SourceType
{
    Text = 0,
    Pdf  = 1,
    Web  = 2
}
